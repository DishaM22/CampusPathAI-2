import { useState } from "react";
import "./qr.css";

const STATUS = {
  active: { label: "Ready to scan", tone: "ok" },
  used: { label: "Attendance recorded", tone: "done" },
  cancelled: { label: "No longer valid", tone: "bad" },
  suspended: { label: "On hold", tone: "bad" },
  revoked: { label: "Revoked", tone: "bad" },
};

function download(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function svgToPng(svg, size = 1024) {
  return new Promise((resolve, reject) => {
    const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
    const image = new Image();
    image.onload = () => {
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = size;
      const context = canvas.getContext("2d");
      context.fillStyle = "#fff";
      context.fillRect(0, 0, size, size);
      context.imageSmoothingEnabled = false; // keep QR modules sharp
      context.drawImage(image, 0, 0, size, size);
      URL.revokeObjectURL(url);
      canvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error("PNG export failed"))), "image/png");
    };
    image.onerror = () => reject(new Error("Could not draw the QR image"));
    image.src = url;
  });
}

/** One QR with title, status and download buttons. */
export default function QrCard({ title, subtitle, note, svg, status = "active", filename = "campuspath-qr" }) {
  const [error, setError] = useState("");
  const state = STATUS[status] || STATUS.active;
  const usable = status === "active";

  const savePng = async () => {
    setError("");
    try {
      download(await svgToPng(svg), `${filename}.png`);
    } catch (e) {
      setError(e.message);
    }
  };
  const saveSvg = () => download(new Blob([svg], { type: "image/svg+xml" }), `${filename}.svg`);

  return (
    <section className="cpqr-card" aria-label={title}>
      <header className="cpqr-head">
        <h3>{title}</h3>
        <span className={`cpqr-badge cpqr-${state.tone}`}>{state.label}</span>
      </header>
      {subtitle && <p className="cpqr-sub">{subtitle}</p>}

      {svg ? (
        <div
          className={`cpqr-frame${usable ? "" : " cpqr-dim"}`}
          role="img"
          aria-label={`${title} QR code`}
          dangerouslySetInnerHTML={{ __html: svg }} // SVG is generated by our own server
        />
      ) : (
        <p className="cpqr-error">The QR image could not be drawn. Refresh the page to try again.</p>
      )}

      {note && <p className="cpqr-note">{note}</p>}
      {svg && (
        <div className="cpqr-actions">
          <button type="button" onClick={savePng}>Download PNG</button>
          <button type="button" className="cpqr-secondary" onClick={saveSvg}>Download SVG</button>
        </div>
      )}
      {error && <p className="cpqr-error" role="alert">{error}</p>}
    </section>
  );
}